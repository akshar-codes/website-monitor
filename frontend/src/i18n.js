export const japaneseTranslations = translations.ja;

export function translate(value, language = "en") {
  if (typeof value !== "string" || language === "en") return value;
  const isRomaji = language === "ja-Latn";
  const copy = translations[isRomaji ? "ja" : language];
  if (!copy) return value;
  const trimmed = value.trim();
  const translated = isRomaji ? romajiTranslations[trimmed] : copy[trimmed];
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

export function translateNode(node, language) {
  return Children.map(node, (child) => {
    if (typeof child === "string") return translate(child, language);
    if (
      !isValidElement(child) ||
      (typeof child.type === "string" &&
        ["code", "pre", "script", "style"].includes(child.type))
    )
      return child;
    if (typeof child.props.children === "function") return child;
    const translatedProps = {};
    for (const prop of ["aria-label", "title", "placeholder", "alt"]) {
      if (typeof child.props[prop] === "string") {
        translatedProps[prop] = translate(child.props[prop], language);
      }
    }
    return cloneElement(
      child,
      translatedProps,
      translateNode(child.props.children, language),
    );
  });
}
